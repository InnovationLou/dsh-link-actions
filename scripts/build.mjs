/**
 * Build the plugin's two halves without a bundler.
 *
 * The client half is one self-contained script, so the only build step is the
 * DSH module-loader handshake: the loader evaluates `client.js` as a plain
 * script and keeps the factory it registers, then materializes the plugin by
 * calling that factory with the shared module table's `require`. The factory
 * supplies `module`/`exports`, so the source file can stay an ordinary
 * `(function (exports) { … })(exports)` module with no imports at all.
 */
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
const id = pkg.name

const body = await readFile(join(root, 'src/client/plugin.js'), 'utf8')
if (body.includes('__ModuleLoader__')) {
  throw new Error('src/client/plugin.js must stay a plain module body; the wrapper owns the loader handshake')
}

const bundle = `/* ${id} client bundle — generated by scripts/build.mjs from src/client/plugin.js */
window.__ModuleLoader__.load({ id: ${JSON.stringify(id)}, factory: (require) => {
var module = { exports: {} }; var exports = module.exports;
${body}
return module.exports; } });
`

await mkdir(join(root, 'lib'), { recursive: true })
await writeFile(join(root, 'lib/client.js'), bundle)
await copyFile(join(root, 'src/index.js'), join(root, 'lib/index.js'))

console.log(`built ${id}: lib/client.js (${bundle.length} bytes), lib/index.js`)
